// extendedFont holds the non-ASCII glyphs the platform cannot do without.
//
// Currency symbols are not decoration. canon.Money.Display renders GBP as a
// pound sign, and a label that drew a box instead would be showing a shopper a
// price with no currency on it, which is the one thing a shelf edge is legally
// required to be unambiguous about.
var extendedFont = map[rune][5]byte{}

// rowsToColumns converts a human-readable glyph, written as seven rows of five
// characters, into the column-major form the renderer uses. Writing these by
// hand in hex is how a currency symbol ends up upside down.
func rowsToColumns(rows [glyphHeight]string) [5]byte {
	var g [5]byte
	for y, row := range rows {
		for x := 0; x < glyphWidth && x < len(row); x++ {
			if row[x] != ' ' && row[x] != '.' {
				g[x] |= 1 << uint(y)
			}
		}
	}
	return g
}

