// glyphFor returns the cell for a rune and whether one existed.
func glyphFor(r rune) ([5]byte, bool) {
	if r >= 0x20 && r <= 0x7E {
		return asciiFont[r-0x20], true
	}
	if g, ok := extendedFont[r]; ok {
		return g, true
	}
	return extendedFont['�'], false
}

// TextWidth returns the pixel width of a string at a scale, excluding the
// trailing inter-character gap.
func TextWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 || scale <= 0 {
		return 0
	}
	return n*glyphAdvance*scale - scale
}

// TextHeight returns the pixel height of a line at a scale.
func TextHeight(scale int) int { return glyphHeight * scale }

// FitScale returns the largest whole-number scale at which a string fits a box,
// or zero if it does not fit at all.
//
// Whole numbers only: a price drawn at 3.5x would have rows of pixels twice as
// thick as their neighbours, which on a bistable panel reads as a printing
// defect rather than as a font.
func FitScale(s string, maxW, maxH int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	byWidth := (maxW + 1) / (n * glyphAdvance)
	byHeight := maxH / glyphHeight
	scale := byWidth
	if byHeight < scale {
		scale = byHeight
	}
	if scale < 1 {
		return 0
	}
	return scale
}

// DrawText renders a string with its top-left corner at (x, y) and returns the
// x coordinate just past the last glyph.
func (f *Framebuffer) DrawText(x, y int, s string, scale int, ink Ink) int {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, r := range s {
		g, _ := glyphFor(r)
		for col := 0; col < glyphWidth; col++ {
			bits := g[col]
			for row := 0; row < glyphHeight; row++ {
				if bits&(1<<uint(row)) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						f.Set(cx+col*scale+dx, y+row*scale+dy, ink)
					}
				}
			}
		}
		cx += glyphAdvance * scale
	}
	return cx - scale
}

// DrawTextCentred renders a string centred horizontally within a span.
func (f *Framebuffer) DrawTextCentred(x0, x1, y int, s string, scale int, ink Ink) {
	w := TextWidth(s, scale)
	f.DrawText(x0+(x1-x0-w)/2, y, s, scale, ink)
}

// DrawTextRight renders a string right-aligned to x1.
func (f *Framebuffer) DrawTextRight(x1, y int, s string, scale int, ink Ink) {
	f.DrawText(x1-TextWidth(s, scale), y, s, scale, ink)
}
