// ---------------------------------------------------------------------------
// Bitmap font
//
// A 5x7 cell, scaled by whole numbers. Whole-number scaling and no antialiasing
// are not simplifications: an electrophoretic panel has two or three ink states
// and no greys to antialias with, so a font that produced them would be
// quantised back to hard edges by the display controller anyway — badly. Every
// commercial electronic shelf label draws exactly like this.
//
// The glyphs are the classic 5x7 terminal set, stored column-major with bit 0
// at the top of the cell, which is the layout the display controller's own
// character generator uses.
// ---------------------------------------------------------------------------

// glyphWidth and glyphHeight are the font cell. advance includes the one-pixel
// gap that separates characters.
const (
	glyphWidth   = 5
	glyphHeight  = 7
	glyphAdvance = glyphWidth + 1
)

